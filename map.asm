; БИБЛИОТЕКА КАРТЫ (map.asm) - ПОДКЛЮЧИЛ И ЗАБЫЛ (ПОДДЕРЖКА ЦВЕТА!) (НАПИСАННО GEMINI)
; ============================================================================
section _TEXT class=CODE
global map_load
global map_find_player

; ----------------------------------------------------------------------------
; Загружает цветной бинарный файл карты (4000 байт) сразу в видеопамять
; DX должен содержать указатель на имя файла!
; ----------------------------------------------------------------------------
map_load:
    pusha
    push es

    ; 1. Открываем файл (DX уже содержит имя файла!)
    mov ah, 3Dh
    mov al, 0
    int 21h
    jc .exit_error
    mov [map_handle], ax

    ; 2. Настраиваемся на видеопамять экрана (0xB800)
    mov ax, 0xB800
    mov es, ax
    xor di, di          ; DI = 0 (Начало экрана)

    ; 3. ЧИТАЕМ СРАЗУ ВСЕ 4000 БАЙТ (Символы + Цвета) НАПРЯМУЮ В ВИДЕОПАМЯТЬ!
    mov ah, 3Fh
    mov bx, [map_handle]
    mov cx, 4000        ; Ровно 4000 байт (80x25x2)
    push ds             ; Сохраняем DS
    push es
    pop ds              ; Делаем DS = 0xB800, чтобы int 21h читал сразу в видеопамять
    xor dx, dx          ; DX = 0 (смещение в 0xB800)
    int 21h
    pop ds              ; Возвращаем DS обратно

.close_file:
    mov ah, 3Eh
    mov bx, [map_handle]
    int 21h

.exit_error:
    pop es
    popa
    ret

; ----------------------------------------------------------------------------
; Ищет символ '@' на экране, стирает его и возвращает координаты в DI
; ----------------------------------------------------------------------------
map_find_player:
    push es
    push ax
    push cx

    mov ax, 0xB800
    mov es, ax
    xor di, di
    mov cx, 2000        ; 2000 клеток на экране

.scan:
    mov al, [es:di]     ; Берем символ с экрана
    cmp al, '@'         ; Это спавн?
    je .found
    add di, 2           ; Идем к следующей клетке
    loop .scan
    
    xor di, di          ; Если не нашли, возвращаем 0
    jmp .done

.found:
    ; Берем цвет, который был под '@' (в байте es:di+1), и пишем туда просто пробел ' '
    mov byte [es:di], ' ' 

.done:
    pop cx
    pop ax
    pop es
    ret

; ============================================================================
; ДАННЫЕ БИБЛИОТЕКИ
; ============================================================================
section _BSS class=BSS
    map_handle resw 1